import {convexTest} from "convex-test";
import {beforeEach,expect,test} from "vitest";
import schema from "../../convex/schema";
import {modules} from "../setup";
import {api} from "../../convex/_generated/api";
const idn=(sub:string,email:string)=>({tokenIdentifier:`https://clerk.test|${sub}`,subject:sub,name:sub,email});
const ok={name:"Cordless drill",category:"Power tools",condition:"Good",description:"18V"};
beforeEach(()=>{process.env.ADMIN_EMAILS="boss@lendloop.test";});
async function setup(){const t=convexTest(schema,modules);
  const as=async(sub:string,email:string)=>{const c=t.withIdentity(idn(sub,email));const id=await c.mutation(api.users.mutations.store,{});return{c,id};};
  return{t,awa:await as("awa","awa@x.test"),koffi:await as("koffi","koffi@x.test"),boss:await as("boss","boss@lendloop.test")};}
test("signed-out visitors cannot create a tool",async()=>{const t=convexTest(schema,modules);
  await expect(t.mutation(api.tools.mutations.create,ok)).rejects.toMatchObject({data:{code:"UNAUTHENTICATED"}});});
test("invalid input is rejected",async()=>{const{awa}=await setup();
  await expect(awa.c.mutation(api.tools.mutations.create,{...ok,name:" "})).rejects.toMatchObject({data:{code:"INVALID"}});
  await expect(awa.c.mutation(api.tools.mutations.create,{...ok,category:"Weapons"})).rejects.toMatchObject({data:{code:"INVALID"}});});
test("a signed-in user can create and see their own tool",async()=>{const{awa}=await setup();
  await awa.c.mutation(api.tools.mutations.create,ok);const mine=await awa.c.query(api.tools.queries.listMine,{});
  expect(mine.length).toBe(1);expect(mine[0].isMine).toBe(true);expect(mine[0].available).toBe(true);});
test("the owner can edit, another user cannot",async()=>{const{awa,koffi}=await setup();
  const id=await awa.c.mutation(api.tools.mutations.create,ok);
  await awa.c.mutation(api.tools.mutations.update,{toolId:id,...ok,name:"Hammer drill"});
  expect((await awa.c.query(api.tools.queries.listMine,{}))[0].name).toBe("Hammer drill");
  await expect(koffi.c.mutation(api.tools.mutations.update,{toolId:id,...ok})).rejects.toMatchObject({data:{code:"FORBIDDEN"}});});
test("another user cannot delete, the owner and an admin can",async()=>{const{awa,koffi,boss}=await setup();
  const a=await awa.c.mutation(api.tools.mutations.create,ok);const b=await awa.c.mutation(api.tools.mutations.create,{...ok,name:"Saw"});
  await expect(koffi.c.mutation(api.tools.mutations.remove,{toolId:a})).rejects.toMatchObject({data:{code:"FORBIDDEN"}});
  await awa.c.mutation(api.tools.mutations.remove,{toolId:a});await boss.c.mutation(api.tools.mutations.remove,{toolId:b});
  expect((await awa.c.query(api.tools.queries.listMine,{})).length).toBe(0);});
test("an admin cannot edit someone else's tool",async()=>{const{awa,boss}=await setup();const id=await awa.c.mutation(api.tools.mutations.create,ok);
  await expect(boss.c.mutation(api.tools.mutations.update,{toolId:id,...ok})).rejects.toMatchObject({data:{code:"FORBIDDEN"}});});
test("a deleted tool disappears from every list",async()=>{const{t,awa}=await setup();const id=await awa.c.mutation(api.tools.mutations.create,ok);
  await awa.c.mutation(api.tools.mutations.remove,{toolId:id});
  expect((await t.query(api.tools.queries.listPublic,{})).length).toBe(0);expect((await awa.c.query(api.tools.queries.listAll,{})).length).toBe(0);});
test("the public list shows only name and category, no owner details",async()=>{const{t,awa}=await setup();
  await awa.c.mutation(api.tools.mutations.create,ok);const pub=await t.query(api.tools.queries.listPublic,{});
  expect(Object.keys(pub[0]).sort()).toEqual(["_id","category","name"]);});
test("listAll requires sign-in and shows the owner name",async()=>{const{t,awa,koffi}=await setup();await awa.c.mutation(api.tools.mutations.create,ok);
  await expect(t.query(api.tools.queries.listAll,{})).rejects.toMatchObject({data:{code:"UNAUTHENTICATED"}});
  const all=await koffi.c.query(api.tools.queries.listAll,{});expect(all[0].ownerName).toBe("awa");expect(all[0].isMine).toBe(false);});
test("a tool out on loan is hidden from the public list and cannot be deleted",async()=>{const{t,awa,koffi}=await setup();
  const id=await awa.c.mutation(api.tools.mutations.create,ok);
  await t.run(c=>c.db.insert("loans",{toolId:id,borrowerId:koffi.id,lenderId:awa.id,startDate:"2000-01-01",endDate:"2000-01-02",status:"approved"}));
  expect((await t.query(api.tools.queries.listPublic,{})).length).toBe(0);
  expect((await awa.c.query(api.tools.queries.listMine,{}))[0].available).toBe(false);
  await expect(awa.c.mutation(api.tools.mutations.remove,{toolId:id})).rejects.toMatchObject({data:{code:"INVALID"}});});
