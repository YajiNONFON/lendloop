import {convexTest} from "convex-test";
import {beforeEach,expect,test} from "vitest";
import schema from "../../convex/schema";
import {modules} from "../setup";
import {api} from "../../convex/_generated/api";
const idn=(sub:string,email:string)=>({tokenIdentifier:`https://clerk.test|${sub}`,subject:sub,name:sub,email});
const d=(n:number)=>new Date(Date.now()+n*864e5).toISOString().slice(0,10);
const tool={name:"Cordless drill",category:"Power tools",condition:"Good",description:"18V"};
beforeEach(()=>{process.env.ADMIN_EMAILS="boss@lendloop.test";});
async function setup(){const t=convexTest(schema,modules);
  const as=async(sub:string)=>{const c=t.withIdentity(idn(sub,`${sub}@x.test`));const id=await c.mutation(api.users.mutations.store,{});return{c,id};};
  const awa=await as("awa"),koffi=await as("koffi"),nadia=await as("nadia");
  const toolId=await awa.c.mutation(api.tools.mutations.create,tool);
  return{t,awa,koffi,nadia,toolId};}
test("signed-out visitors cannot request",async()=>{const{t,toolId}=await setup();
  await expect(t.mutation(api.loans.mutations.request,{toolId,startDate:d(1),endDate:d(2)})).rejects.toMatchObject({data:{code:"UNAUTHENTICATED"}});});
test("nobody can borrow their own tool",async()=>{const{awa,toolId}=await setup();
  await expect(awa.c.mutation(api.loans.mutations.request,{toolId,startDate:d(1),endDate:d(2)})).rejects.toMatchObject({data:{code:"INVALID"}});});
test("past and reversed dates are rejected",async()=>{const{koffi,toolId}=await setup();
  await expect(koffi.c.mutation(api.loans.mutations.request,{toolId,startDate:d(-1),endDate:d(2)})).rejects.toMatchObject({data:{code:"INVALID"}});
  await expect(koffi.c.mutation(api.loans.mutations.request,{toolId,startDate:d(5),endDate:d(2)})).rejects.toMatchObject({data:{code:"INVALID"}});});
test("a deleted tool cannot be requested",async()=>{const{awa,koffi,toolId}=await setup();
  await awa.c.mutation(api.tools.mutations.remove,{toolId});
  await expect(koffi.c.mutation(api.loans.mutations.request,{toolId,startDate:d(1),endDate:d(2)})).rejects.toMatchObject({data:{code:"NOT_FOUND"}});});
test("a request is visible to both sides and to nobody else",async()=>{const{awa,koffi,nadia,toolId}=await setup();
  await koffi.c.mutation(api.loans.mutations.request,{toolId,startDate:d(1),endDate:d(3)});
  const b=await koffi.c.query(api.loans.queries.listMine,{});const l=await awa.c.query(api.loans.queries.listMine,{});
  expect(b[0].role).toBe("borrower");expect(b[0].status).toBe("pending");expect(l[0].role).toBe("lender");expect(l[0].borrowerName).toBe("koffi");
  expect((await nadia.c.query(api.loans.queries.listMine,{})).length).toBe(0);});
test("only the lender can approve or decline",async()=>{const{awa,koffi,nadia,toolId}=await setup();
  const id=await koffi.c.mutation(api.loans.mutations.request,{toolId,startDate:d(1),endDate:d(3)});
  await expect(koffi.c.mutation(api.loans.mutations.decide,{loanId:id,decision:"approve"})).rejects.toMatchObject({data:{code:"FORBIDDEN"}});
  await expect(nadia.c.mutation(api.loans.mutations.decide,{loanId:id,decision:"approve"})).rejects.toMatchObject({data:{code:"FORBIDDEN"}});
  await awa.c.mutation(api.loans.mutations.decide,{loanId:id,decision:"approve"});
  expect((await koffi.c.query(api.loans.queries.listMine,{}))[0].status).toBe("approved");});
test("a declined loan cannot be approved afterwards",async()=>{const{awa,koffi,toolId}=await setup();
  const id=await koffi.c.mutation(api.loans.mutations.request,{toolId,startDate:d(1),endDate:d(3)});
  await awa.c.mutation(api.loans.mutations.decide,{loanId:id,decision:"decline"});
  await expect(awa.c.mutation(api.loans.mutations.decide,{loanId:id,decision:"approve"})).rejects.toMatchObject({data:{code:"INVALID"}});});
test("two approved loans cannot overlap on the same tool",async()=>{const{awa,koffi,nadia,toolId}=await setup();
  const a=await koffi.c.mutation(api.loans.mutations.request,{toolId,startDate:d(1),endDate:d(4)});
  const b=await nadia.c.mutation(api.loans.mutations.request,{toolId,startDate:d(3),endDate:d(6)});
  await awa.c.mutation(api.loans.mutations.decide,{loanId:a,decision:"approve"});
  await expect(awa.c.mutation(api.loans.mutations.decide,{loanId:b,decision:"approve"})).rejects.toMatchObject({data:{code:"INVALID"}});
  await expect(nadia.c.mutation(api.loans.mutations.request,{toolId,startDate:d(2),endDate:d(2)})).rejects.toMatchObject({data:{code:"INVALID"}});
  const c=await nadia.c.mutation(api.loans.mutations.request,{toolId,startDate:d(7),endDate:d(8)});
  await awa.c.mutation(api.loans.mutations.decide,{loanId:c,decision:"approve"});});
test("the borrower can cancel a pending request, not an approved one",async()=>{const{awa,koffi,toolId}=await setup();
  const a=await koffi.c.mutation(api.loans.mutations.request,{toolId,startDate:d(1),endDate:d(2)});
  await expect(awa.c.mutation(api.loans.mutations.cancel,{loanId:a})).rejects.toMatchObject({data:{code:"FORBIDDEN"}});
  await koffi.c.mutation(api.loans.mutations.cancel,{loanId:a});
  const b=await koffi.c.mutation(api.loans.mutations.request,{toolId,startDate:d(1),endDate:d(2)});
  await awa.c.mutation(api.loans.mutations.decide,{loanId:b,decision:"approve"});
  await expect(koffi.c.mutation(api.loans.mutations.cancel,{loanId:b})).rejects.toMatchObject({data:{code:"INVALID"}});});
test("only the lender marks a loan returned, and the tool is free again",async()=>{const{t,awa,koffi,toolId}=await setup();
  const id=await koffi.c.mutation(api.loans.mutations.request,{toolId,startDate:d(0),endDate:d(2)});
  await expect(awa.c.mutation(api.loans.mutations.markReturned,{loanId:id})).rejects.toMatchObject({data:{code:"INVALID"}});
  await awa.c.mutation(api.loans.mutations.decide,{loanId:id,decision:"approve"});
  expect((await t.query(api.tools.queries.listPublic,{})).length).toBe(0);
  await expect(koffi.c.mutation(api.loans.mutations.markReturned,{loanId:id})).rejects.toMatchObject({data:{code:"FORBIDDEN"}});
  await awa.c.mutation(api.loans.mutations.markReturned,{loanId:id});
  expect((await t.query(api.tools.queries.listPublic,{})).length).toBe(1);});
test("an approved loan past its end date is flagged overdue",async()=>{const{t,awa,koffi,toolId}=await setup();
  await t.run(c=>c.db.insert("loans",{toolId,borrowerId:koffi.id,lenderId:awa.id,startDate:d(-6),endDate:d(-2),status:"approved"}));
  expect((await awa.c.query(api.loans.queries.listMine,{}))[0].overdue).toBe(true);});
